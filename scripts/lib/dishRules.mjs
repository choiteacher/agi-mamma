// 급식 요리명 정리와 "34개월 주의 가능" 표시 규칙.
// 요리명만 보고 붙이는 일반적인 주의 표시일 뿐이며, 최종 판단은 부모가 한다.

// 알레르기 번호 "(1.2.5.)", "1.2.5." 같은 표기와 괄호 안 표기, 장식 기호를 지운다.
export function cleanDishName(raw) {
  return raw
    .replace(/<[^>]*>/g, ' ')
    .replace(/\([^)]*\)|\[[^\]]*\]|\{[^}]*\}|（[^）]*）/g, ' ')
    .replace(/(\d+\.)+\d*/g, ' ')
    .replace(/[*#@&$%^!~+★☆●○◎◆◇■□▲△※`'"]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/_[^_\s]*$/, '') // "백미밥_원주" 같은 출처 꼬리표
    .replace(/\s+\d+$/, '') // "배추김치 1" 같은 번호 꼬리표
    .replace(/^[\-_./,]+|[\-_./,]+$/g, '')
    .trim();
}

export function splitDishes(ddishNm) {
  return ddishNm
    .split(/<br\s*\/?>|\n/i)
    .map(cleanDishName)
    .filter((n) => n.length >= 2 && !/^\d+$/.test(n));
}

// ---------- 일정 대상이 아닌 항목 (우유/음료/과일/흰밥) ----------
// 이름이 음료로 끝나야 한다("우유달걀찜"은 요리).
const DRINK = /(우유|요구르트|요거트|주스|쥬스|음료|두유|식혜|수정과|에이드|스무디|라떼|미숫가루|차)$/;
// 이름 전체가 과일이어야 한다("배추김치"가 "배"로 시작해도 과일이 아님). "잘게자른 포도" 같은 손질 표기는 허용.
const FRUIT =
  /^(잘게\s?자른|썬|조각)?\s?(사과|배|포도|샤인머스[캣켓]|귤|감귤|금귤|오렌지|바나나|수박|참외|멜론|딸기|키위|골드키위|복숭아|자두|파인애플|망고|블루베리|체리|방울토마토|토마토|천혜향|한라봉|레드향|청포도|거봉|감|단감|홍시|석류|과일|제철과일|모듬과일)$/;
const PLAIN_RICE = /(쌀|현미|잡곡|흑미|보리|백미|기장|찹쌀|귀리|수수|조|차조|렌틸콩|병아리콩|서리태|검정콩|강낭콩|완두콩|콩|흰|친환경)?밥$/;
const COMPOSED_RICE =
  /짜장밥|카레밥|하이라이스|잡채밥|볶음밥|비빔밥|덮밥|주먹밥|김밥|초밥|오므라이스|컵밥|국밥|영양밥|솥밥|무밥|콩나물밥|곤드레|약밥|유부초밥|쌈밥/;

export function excludedReason(name) {
  if (DRINK.test(name)) return '음료/유제품';
  if (FRUIT.test(name)) return '과일';
  if (PLAIN_RICE.test(name) && !COMPOSED_RICE.test(name)) return '밥(일정 제외)';
  return null;
}

// ---------- 김치류 ----------
// 사용자 지침: 김치는 다른 요리로 바꾸지 않고, 물에 씻어서 먹이는 방법을 제안한다.
const KIMCHI = /김치|깍두기|겉절이|섞박지|총각|열무김치|파김치|갓김치|백김치|동치미|나박|오이소박이/;
export const isKimchi = (name) => KIMCHI.test(name);
export const KIMCHI_TIP = '물에 헹궈 양념을 씻어 내고 잘게 썰어서 (씻은 김치)';

// ---------- 매운 요리 → 안 매운 대체안 ----------
// [패턴, 대체 요리명] 위에서부터 먼저 맞는 것을 쓴다.
const MILD_MAP = [
  [/제육/, '간장 돼지불고기'],
  [/닭볶음탕|닭도리탕/, '간장 닭찜'],
  [/찜닭/, '간장 찜닭(고추 빼고)'],
  [/떡볶이|떡볶기/, '궁중떡볶이(간장)'],
  [/라볶이/, '간장 라볶이'],
  [/쭈꾸미|주꾸미|낙지/, '간장 쭈꾸미볶음'],
  [/오징어.*볶음|오징어.*두루치기/, '간장 오징어볶음'],
  [/두루치기/, '간장 두루치기'],
  [/육개장/, '소고기무국'],
  [/짬뽕/, '맑은 해물국수(백짬뽕)'],
  [/고추장찌개/, '된장찌개'],
  [/순두부찌개/, '맑은 순두부국'],
  [/부대찌개/, '맑은 소시지 콩나물국'],
  [/동태찌개|동태탕|알탕|매운탕/, '맑은 생선국(지리)'],
  [/감자탕|뼈해장국/, '맑은 돼지등뼈 감잣국'],
  [/마파두부/, '간장 두부덮밥'],
  [/비빔국수|쫄면/, '간장 비빔국수'],
  [/비빔밥/, '간장 비빔밥(고추장 빼고)'],
  [/양념치킨|닭강정/, '간장 닭강정'],
  [/불닭|매운|마라|고추|청양|칠리|핫소스|짬뽕|불고기.*매콤|매콤/, null]
];
const SPICY_HINT =
  /고추장|고춧가루|매운|매콤|얼큰|칼칼|청양|불닭|마라|칠리|핫소스|짬뽕|육개장|제육|닭볶음탕|닭도리탕|떡볶이|떡볶기|라볶이|쭈꾸미|주꾸미|낙지|두루치기|부대찌개|순두부찌개|고추장찌개|매운탕|동태찌개|감자탕|뼈해장국|마파두부|비빔국수|쫄면|양념치킨|닭강정|오징어.*볶음/;
// 이름만으로는 알 수 없지만 학교 급식에서 고춧가루를 자주 쓰는 형태
const MAYBE_SPICY = /무침|조림|생채|겉절이|볶음$/;

// 이미 안 매운 버전임을 이름에 밝힌 요리 (안매운육개장, 간장비빔국수, 백짬뽕 등)
const ALREADY_MILD = /^(안\s?매운|순한|간장|맑은|하얀|백짬뽕|백떡볶이)/;

export function spicyInfo(name) {
  if (isKimchi(name)) return { level: 'kimchi', mild: KIMCHI_TIP };
  if (ALREADY_MILD.test(name)) return { level: 'none', mild: null };
  if (SPICY_HINT.test(name)) {
    const hit = MILD_MAP.find(([re]) => re.test(name));
    const mild = hit && hit[1] ? hit[1] : `${name} (고춧가루·고추장 빼고 간장/소금 간)`;
    return { level: 'spicy', mild };
  }
  if (MAYBE_SPICY.test(name)) return { level: 'maybe', mild: `고춧가루 없이 간장/소금으로` };
  return { level: 'none', mild: null };
}

// ---------- 34개월 주의 표시 ----------
const CAUTIONS = [
  [
    '질식위험',
    /견과|땅콩|아몬드|호두|잣|캐슈|피스타치오|방울토마토|포도|떡|경단|인절미|소시지|비엔나|메추리알|젤리|곤약|사탕|팝콘|마시멜로|강정|떡갈비/
  ],
  ['가시', /고등어|삼치|꽁치|갈치|조기|가자미|임연수|명태|동태|코다리|생선|연어|참치(?!캔)|도미|멸치(?!볶음)|장어|굴비|이면수/],
  ['날것', /(?<!숙)회$|(?<!숙)회무침|육회|생굴|날치알|(?<!유부)초밥|사시미|생연어/],
  ['질감(질김/딱딱)', /오징어|쥐포|진미채|문어|낙지|쭈꾸미|주꾸미|건새우|누룽지|떡|우엉|연근|육포|건어물|쫄면|도라지/],
  [
    '난이도 높음',
    /튀김|까스|가스|커틀릿|탕수|강정|만두|전병|크로켓|고로케|돈가스|깐풍|유린기|칠리새우|파스타|그라탕|케이크|빵|쿠키|머핀|피자|와플/
  ],
  ['꿀/카페인 확인', /꿀|허니|커피|초코|코코아|녹차/]
];

export function cautionsFor(name) {
  const list = CAUTIONS.filter(([, re]) => re.test(name)).map(([label]) => label);
  const spicy = spicyInfo(name);
  if (spicy.level === 'spicy') list.unshift('맵기');
  if (spicy.level === 'maybe') list.unshift('맵기(양념 확인)');
  if (spicy.level === 'kimchi') list.unshift('김치류(씻어서)');
  return list;
}

// ---------- 조리 수고 (초보 기준, 0~3) ----------
// 식단 세트를 통째로 고를 때 "만들기 쉬운 날"을 고르는 데만 쓴다. 요리를 빼거나 바꾸는 데 쓰지 않는다.
const EFFORT_0 = /^(김치|배추김치|깍두기|.*김치)$|김자반|김구이|^김$|조미김|구운김|치즈$|^(.*)?밥$/; // 사 오거나 밥솥
const EFFORT_3 =
  /튀김|까스|가스$|커틀릿|탕수|강정|전$|전병|동그랑땡|부침|육전|만두(?!국)|떡갈비|완자|잡채|스테이크|그라탕|빵|케이크|머핀|쿠키|크로켓|고로케|피자/;
const EFFORT_1 = /국$|탕$|찌개$|스프$|수프$|장국|나물$|무침$|숙회$|생채$|계란찜|달걀찜|삶은|찐/;

export function cookEffort(name) {
  if (EFFORT_0.test(name) && !/볶음밥|비빔밥|덮밥|주먹밥|김밥|짜장밥|카레밥|유부초밥/.test(name)) return 0;
  if (EFFORT_3.test(name)) return 3;
  if (EFFORT_1.test(name)) return 1;
  return 2;
}
